def enrich(f):
    hay = " ".join(str(f.get(k, "")) for k in ("name", "category", "desc")).lower().replace(" ", "")
    for keys, cat, desc, steps, impact, fix in T:
        if any(k.lower().replace(" ", "") in hay for k in keys):
            f.setdefault("category", cat)
            if not f.get("category") or f["category"] in ("未分类", "补充"):
                f["category"] = cat
            f["desc"] = f.get("desc") or desc
            f["steps"] = f.get("steps") or steps
            f["impact"] = f.get("impact") or impact
            f["fix"] = f.get("fix") or fix
            return True
    return False


def main():
    src = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[3]) if len(sys.argv) > 3 and sys.argv[2] == "-o" else src.with_name(src.stem + "-enriched.json")
    data = json.loads(src.read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data = data.get("findings", [])
    hit = 0
    for f in data:
        if enrich(f):
            hit += 1
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"已补全 {hit}/{len(data)} 条 → {out}")
    for f in data:
        print(f"  [{f.get('category','?'):<10}] {str(f.get('name',''))[:38]:<38} 描述={'有' if f.get('desc') else '无'} 步骤={'有' if f.get('steps') else '无'}")


if __name__ == "__main__":
    main()
